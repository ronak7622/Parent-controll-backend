export const localizeFeatureItem = (rawText: string, lang: string = 'en'): string => {
  const safeLang = ['en', 'hi', 'gu', 'es', 'fr'].includes(lang) ? lang : 'en';
  if (safeLang === 'en') return rawText;

  // Exact match
  if (FEATURE_I18N[rawText] && FEATURE_I18N[rawText][safeLang]) {
    return FEATURE_I18N[rawText][safeLang];
  }

  // Device text
  if (rawText.toLowerCase().includes('device connect')) {
    if (rawText.toLowerCase().includes('unlimited')) {
      const map: Record<string, string> = {
        hi: 'असीमित डिवाइस कनेक्ट',
        gu: 'અમર્યાદિત ડિવાઇસ કનેક્ટ',
        es: 'Dispositivos ilimitados conectados',
        fr: 'Appareils illimités connectés',
      };
      return map[safeLang] || rawText;
    } else {
      const map: Record<string, string> = {
        hi: '1 डिवाइस कनेक्ट',
        gu: '1 ડિવાઇસ કનેક્ટ',
        es: '1 dispositivo conectado',
        fr: '1 appareil connecté',
      };
      return map[safeLang] || rawText;
    }
  }

  // Storage text
  if (rawText.toLowerCase().includes('storage')) {
    if (rawText.toLowerCase().includes('100 mb')) {
      const map: Record<string, string> = {
        hi: '100 MB सुरक्षित क्लाउड स्टोरेज',
        gu: '100 MB સુરક્ષિત ક્લાઉડ સ્ટોરેજ',
        es: '100 MB de almacenamiento seguro',
        fr: '100 Mo de stockage cloud sécurisé',
      };
      return map[safeLang] || rawText;
    }
    if (rawText.toLowerCase().includes('20 gb')) {
      const map: Record<string, string> = {
        hi: '20 GB सुरक्षित क्लाउड स्टोरेज',
        gu: '20 GB સુરક્ષિત ક્લાઉડ સ્ટોરેજ',
        es: '20 GB de almacenamiento seguro',
        fr: '20 Go de stockage cloud sécurisé',
      };
      return map[safeLang] || rawText;
    }
  }

  return rawText;
};
